// คำพูดของตัวละครเมื่อแตะ — เลือกตามสถานการณ์ พร้อมท่าทางที่เข้ากับคำพูด
// เดือนเป็นจันทรคติ: 0 = เดือนอ้าย … 4 = เดือนห้า (สงกรานต์) … 11 = เดือนสิบสอง
import { BALANCE as B } from '../engine/balance';
import * as E from '../engine/core';

export interface Speech { text: string; anim?: string }
type Line = [string, string?];

const pick = <T>(a: T[]) => a[Math.floor(Math.random() * a.length)];

export function speechFor(g: E.GameState, ctx: { rain: boolean; war: boolean; month: number }): Speech {
  const L = g.life, age = E.ageOf(L), lines: Line[] = [];
  const add = (...ls: Line[]) => lines.push(...ls);

  // ---- บ้านเมืองและฤดูกาล ----
  if (ctx.war) add(['ได้ยินว่าทัพหลวงยกออกไปอีกแล้ว…', 'surprised'], ['ขออย่าให้ถูกเกณฑ์ไปแนวหน้าเลย', 'sad'], ['ข้าศึกมาเมื่อไร ข้าจะไม่หนี!', 'staff'], ['ช่วงศึกแบบนี้ ข้าวของแพงไปหมด']);
  if (ctx.rain) add(['ฝนตกอีกแล้ว นาคงได้น้ำเต็มทุ่ง', 'rain'], ['หน้าฝนทีไร ทางเดินเป็นโคลนทุกที', 'rain'], ['ฝนแบบนี้ นอนฟังเสียงฝนสบายที่สุด', 'sleep']);
  if (ctx.month === 4) add(['สงกรานต์แล้ว! ไปสรงน้ำพระกัน', 'happy'], ['ปีใหม่ทั้งที ขอพรผู้ใหญ่หน่อย', 'meditate']);
  if (ctx.month >= 7 && ctx.month <= 10) add(['เข้าพรรษาแล้ว ตั้งใจถือศีลสักหน่อย', 'meditate']);
  if (ctx.month === 11) add(['เดือนสิบสองน้ำนองเต็มตลิ่ง ลอยกระทงกันเถอะ', 'happy']);
  if (ctx.month <= 1) add(['ลมหนาวมาแล้ว ข้าวในนาเหลืองอร่าม', 'forage'], ['ถึงหน้าเกี่ยวข้าว คนทั้งหมู่บ้านลงแขกกัน', 'carry']);
  if (ctx.month >= 3 && ctx.month <= 5) add(['ร้อนเหลือเกิน อยากลงไปเล่นน้ำในคลอง'], ['หน้าแล้ง บ่อน้ำเริ่มแห้งแล้ว', 'sad']);

  // ---- ร่างกาย ----
  if (L.health < 0.3) add(['ช่วงนี้รู้สึกไม่ค่อยมีแรง…', 'sad'], ['ปวดเมื่อยไปทั้งตัว คงถึงวัยแล้วสินะ', 'sad'], ['ต้องหาหมอยามาดูอาการสักหน่อย']);
  else if (age >= 55) add(['แก่แล้ว เดินไม่ค่อยไหวเหมือนก่อน'], ['เล่าเรื่องสมัยหนุ่มให้หลานฟังดีกว่า', 'happy']);

  // ---- ช่วงวัยและงาน ----
  if (age < B.careerMinAge) {
    add(['โตขึ้นอยากเป็นอะไรดี…'], ['แม่บอกว่าห้ามไปเล่นน้ำคนเดียว'], ['วิ่งเล่นกับเพื่อนแถวท่าน้ำดีกว่า', 'happy']);
    if (!L.childJob) add(['วันนี้จะไปช่วยงานอะไรดีนะ'], ['ผู้ใหญ่เขาทำงานกันหมด ข้าก็อยากช่วยบ้าง']);
    if (L.childJob === 'หาของป่า') add(['เมื่อวานเจอเห็ดโคนดอกใหญ่เท่าฝ่ามือ!', 'forage'], ['ในป่ามีรอยเสือด้วยนะ น่ากลัวจัง', 'surprised']);
    if (L.childJob === 'งานวัด') add(['หลวงพ่อสอนให้อ่านเขียนด้วย', 'read'], ['กวาดลานวัดเสร็จ จะได้ขนมจากโรงครัว', 'sweep']);
    if (L.childJob === 'คาราวาน') add(['พ่อค้าเล่าว่าเมืองจีนไกลมากเลย', 'pole'], ['หาบของหนักจัง แต่ได้ค่าแรงดี', 'pole']);
  } else if (!L.career) {
    add(['ถึงเวลาต้องเลือกทางชีวิตแล้ว'], ['จะเป็นทหาร พ่อค้า หรือขุนนางดี?'], ['ทางไหนก็ได้ ขอให้ได้ช่วยบ้านเมือง']);
  } else {
    const blk = E.promoteBlock(g);
    if (blk === null) add(['พร้อมแล้ว! ไปยื่นเรื่องขอเลื่อนยศดีกว่า', 'happy']);
    if (blk === 'affection') add(['ฝีมือพอแล้ว แต่นายยังไม่เห็นผลงาน…', 'sad']);
    if (blk === 'money') add(['อยากยื่นเรื่องเลื่อนยศ แต่เงินยังไม่พอ', 'sad']);
    if (blk === 'house') add(['ยศสูงขึ้นแล้วยังอยู่บ้านเก่า คนเขาจะว่าเอาได้']);
    if (blk === 'stat') add(['ต้องฝึกให้หนักกว่านี้อีกหน่อย', 'staff'], ['งานวันนี้เหนื่อย แต่ก็ได้เรียนรู้']);
    const c = L.career;
    if (c === 'ทหาร') add(['ซ้อมหอกทุกเช้า แขนแข็งขึ้นเยอะเลย', 'spear'], ['นายกองดุมาก แต่ก็ใจดี'], ['คืนนี้ต้องเข้าเวรยาม']);
    if (c === 'พ่อค้า') add(['สำเภาจีนจะเข้าท่าเดือนหน้า ต้องเตรียมสินค้า', 'pole'], ['ซื้อถูกขายแพง หัวใจของการค้า', 'happy']);
    if (c === 'เกษตรกร') add(['ปีนี้น้ำดี ข้าวคงงาม', 'forage'], ['ควายของข้าขยันกว่าคนอีก', 'carry']);
    if (c === 'บริหาร') add(['หนังสือราชการกองเท่าภูเขา', 'read'], ['ตัดสินความวันนี้ ยากเหลือเกิน', 'read']);
    if (c === 'ปุโรหิต') add(['ฤกษ์งามยามดีต้องดูให้แม่น', 'candle'], ['ท่องคาถาจนจำขึ้นใจแล้ว', 'candle']);
    if (c === 'สายลับ') add(['ชู่ว์… มีคนตามมาหรือเปล่า', 'sneak'], ['ข่าวที่ได้มาวันนี้ ต้องรีบส่งให้นาย', 'sneak']);
    if (L.track === 'dark') add(['ทางที่เลือกเดินนี้… ไม่มีวันหันหลังกลับแล้ว'], ['ใครขวางทาง คนนั้นต้องหลีกไป']);
    if (L.track === 'light') add(['ทำงานด้วยใจซื่อ สักวันฟ้าคงเห็น', 'meditate']);
  }

  // ---- สิ่งที่ฝึกอยู่ ----
  const TRAIN: Record<string, Line> = {
    'ความรู้': ['อ่านตำราไปอีกหน้า ยิ่งรู้ยิ่งรู้ว่าไม่รู้', 'read'], 'พละกำลัง': ['ยกของหนักทุกวัน แข็งแรงขึ้นเยอะ', 'carry'],
    'ต่อสู้': ['ท่ารำไม้วันนี้คล่องขึ้นแล้ว', 'staff'], 'บารมี': ['นั่งสมาธิแล้วใจนิ่งขึ้นเยอะ', 'meditate'],
    'หลบหลีก': ['เดินให้เงียบเหมือนแมว…', 'sneak'], 'ไสยเวทย์': ['เทียนเล่มนี้ปลุกเสกมาเจ็ดวันแล้ว', 'candle'],
    'ไหวพริบ': ['เล่นหมากรุกกับตาแก่ข้างบ้าน ชนะแล้วหนึ่งตา!', 'happy'], 'โภคทรัพย์': ['นับเบี้ยในถุงอีกรอบ… ยังขาดอีกนิด'],
  };
  for (const s of L.train) if (TRAIN[s]) add(TRAIN[s]);
  if (L.path === 'merit') add(['ทำบุญตักบาตรทุกเช้า ใจเบิกบาน', 'meditate']);
  if (L.path === 'work') add(['งานหนักไม่เคยฆ่าใคร', 'carry']);

  // ---- ทรัพย์ บุญ บ้าน ----
  if (g.merit > 50) add(['ทำบุญไว้มาก ใจก็สงบ', 'meditate']);
  if (g.merit > 3000) add(['รู้สึกเหมือนเคยเกิดมาแล้วหลายชาติ…']);
  if (L.money > 5) add(['เก็บเงินได้ไม่น้อย จะเอาไปทำอะไรดีนะ', 'happy']);
  if (L.money < 0.05 && age >= B.careerMinAge) add(['เบี้ยในถุงเหลือไม่กี่อัน…', 'sad']);
  if (L.accommodation >= 4) add(['บ้านหลังนี้กว้างขวาง อยู่สบายจริง', 'happy']);
  if (g.life.idx > 1) add(['บางทีก็ฝันเห็นใบหน้าคนที่ไม่เคยรู้จัก…'], ['ที่นี่… ทำไมรู้สึกคุ้นเคยนัก', 'surprised']);

  // ---- ทั่วไป ----
  add(['อยุธยาวันนี้คึกคักดีจริง'], ['ขอให้บ้านเมืองสงบสุขเถิด', 'meditate'], ['ได้กลิ่นขนมครกจากตลาดน้ำ หอมจัง', 'happy'],
    ['เสียงระฆังวัดดังมาแต่ไกล'], ['เมื่อคืนฝันว่าได้เข้าวัง!', 'surprised'], ['นั่งดูเรือสำเภาลอยผ่านหน้าบ้าน'],
    ['หาว… ง่วงจัง', 'sleep'], ['มีอะไรให้ข้าช่วยไหม?'], ['อย่าจิ้มบ่อยนักสิ จั๊กจี้!', 'happy']);
  const [text, anim] = pick(lines);
  return { text, anim };
}
